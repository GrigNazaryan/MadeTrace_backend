"""Differential test: the Python domain logic must agree with the original JS prototype logic.

tests/fixtures/parity_cases.json was generated by running the prototype's own JavaScript
(logic.js / business.js / order-state.js) over thousands of random inputs.
"""
import json
import math
import os
import unittest

from app.domain import order_state, pricing, schedule

HERE = os.path.dirname(__file__)


def load():
    with open(os.path.join(HERE, "fixtures", "parity_cases.json"), encoding="utf-8") as f:
        return json.load(f)


def js_order(o):
    """Translate a JS-prototype order into the (quote, proof) shape our Python functions take."""
    quotes = o.get("quotes") or []
    quote = quotes[-1] if quotes else None
    proof = o.get("proof")
    return quote, proof, bool(quotes)


class Parity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = load()

    def test_estimate(self):
        for c in self.data["cases"]:
            got = pricing.calculate_print_estimate(c["lines"], c["pricing"], c["products"])
            exp = c["out"]
            self.assertAlmostEqual(got["total"], exp["total"], places=2, msg=json.dumps(c)[:300])
            self.assertEqual(len(got["breakdown"]), len(exp["breakdown"]))
            for g, e in zip(got["breakdown"], exp["breakdown"]):
                self.assertAlmostEqual(g["total"], e["total"], places=2)
                self.assertEqual(g["quantity"], e["quantity"])
                self.assertEqual(g["placements"], e["placements"])

    def test_bulk_adjustment(self):
        codes = {"Choose an adjustment between −100% and +1000%.": "bad_percent",
                 "Select at least one product in this scope.": "empty_scope"}
        for c in self.data["adj"]:
            opt = c["opt"]
            try:
                got = pricing.preview_price_adjustment(c["products"], opt["scope"], opt["selected"], opt["category"], opt["percent"], opt["rounding"])
            except ValueError as err:
                exp = c["out"]
                self.assertIn("error", exp, msg=json.dumps(c))
                self.assertEqual(codes[exp["error"]], str(err))
                continue
            self.assertNotIn("error", c["out"], msg=json.dumps(c))
            self.assertEqual([r["id"] for r in got], [r["id"] for r in c["out"]])
            for g, e in zip(got, c["out"]):
                self.assertAlmostEqual(g["after"], e["after"], places=2, msg=json.dumps(c))

    def test_transitions(self):
        err_map = {
            "Unknown order status.": "unknown_status",
            "Completed orders retain their history. Repeat the order to start new work.": "order_completed",
            "Canceled orders remain closed. Repeat the order to start a new request.": "order_cancelled",
            "Send a quote first.": "quote_required",
            "First obtain acceptance of the latest quote.": "quote_not_accepted",
            "Request a design proof first.": "proof_required",
            "Current design proof still needs approval.": "proof_not_approved",
        }
        for c in self.data["trans"]:
            o = c["order"]
            quote, proof, has_quotes = js_order(o)
            got = order_state.status_change_error(o["status"], c["next"], quote, proof)
            exp = err_map[c["err"]] if c["err"] else None
            self.assertEqual(got, exp, msg=json.dumps(c))
            self.assertEqual(order_state.approval_status(o["status"], quote, proof, has_quotes), c["approval"], msg=json.dumps(c))
            pr = order_state.order_progress(o["status"], o.get("resumeStatus"), quote, proof)
            self.assertEqual(pr["stage"], c["progress"]["stage"], msg=json.dumps(c))
            self.assertEqual(pr["exception"], c["progress"]["exception"], msg=json.dumps(c))
            self.assertEqual(pr["complete"], c["progress"]["complete"], msg=json.dumps(c))

    def test_schedule(self):
        codes = {"Enter valid calendar dates.": "invalid_date",
                 "Production deadline cannot be before the production start.": "deadline_before_start",
                 "Explain the new promised ready date in a customer-visible notice.": "promise_change_needs_comment"}
        for c in self.data["sched"]:
            try:
                got = schedule.validate_schedule(c["prev"], c["nx"], c["c"])
            except ValueError as err:
                self.assertIn("error", c["out"], msg=json.dumps(c))
                self.assertEqual(codes[c["out"]["error"]], str(err), msg=json.dumps(c))
                continue
            self.assertNotIn("error", c["out"], msg=json.dumps(c))
            self.assertEqual(got, c["out"], msg=json.dumps(c))


if __name__ == "__main__":
    unittest.main()
